// Known reports whether the route has a curated label.
func Known(method, routeTemplate string) bool {
	_, ok := labels[method+" "+routeTemplate]
	return ok
}

// Label returns the curated label, or "METHOD template" when unknown.
func Label(method, routeTemplate string) string {
	if l, ok := labels[method+" "+routeTemplate]; ok {
		return l
	}
	return method + " " + routeTemplate
}
